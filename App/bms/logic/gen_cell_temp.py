#!/usr/bin/env python3
"""Generates App/bms/logic/Src/cell_temp_table.c, the 1 mV table that turns a
cell temperature sensor's voltage into 0.1 C (issue 62, cell_temp.h).

    python App/bms/logic/gen_cell_temp.py

The 33 points are the Enepaq Li-ion Building Block datasheet, Rev E
(2026-06-16), page 3, Table 5. Between two points the temperature is linear in
the voltage ("Linear interpolation can be used to calculate more values with
reasonable accuracy", same page), rounded to the nearest 0.1 C with halves away
from the lower point. Integer arithmetic only, so the table is exact and the
same on every machine. Change a point here, run the script, commit both.
CI fails if the committed table differs from what this script writes.
"""

from pathlib import Path

# (temperature in C, sensor voltage in mV)
TABLE_5 = [
    (-40, 2440), (-35, 2420), (-30, 2400), (-25, 2380), (-20, 2350), (-15, 2320),
    (-10, 2270), (-5, 2230), (0, 2170), (5, 2110), (10, 2050), (15, 1990),
    (20, 1920), (25, 1860), (30, 1800), (35, 1740), (40, 1680), (45, 1630),
    (50, 1590), (55, 1550), (60, 1510), (65, 1480), (70, 1450), (75, 1430),
    (80, 1400), (85, 1380), (90, 1370), (95, 1350), (100, 1340), (105, 1330),
    (110, 1320), (115, 1310), (120, 1300),
]

MV_MIN = TABLE_5[-1][1]
MV_MAX = TABLE_5[0][1]

OUT = Path(__file__).resolve().parent / "Src" / "cell_temp_table.c"


def deci_celsius(mv: int) -> int:
    for (t1, v1), (t2, v2) in zip(TABLE_5, TABLE_5[1:]):
        if v2 <= mv <= v1:
            # tenths above t1: (v1 - mv) / (v1 - v2) of (t2 - t1) * 10
            num = (v1 - mv) * (t2 - t1) * 10
            den = v1 - v2
            return t1 * 10 + (2 * num + den) // (2 * den)
    raise ValueError(mv)


def main() -> None:
    assert len(TABLE_5) == 33
    assert all(v1 > v2 for (_, v1), (_, v2) in zip(TABLE_5, TABLE_5[1:]))

    values = [deci_celsius(mv) for mv in range(MV_MIN, MV_MAX + 1)]
    rows = []
    for i in range(0, len(values), 10):
        chunk = values[i:i + 10]
        rows.append(f"    /* {MV_MIN + i:4d} mV */ " + ", ".join(f"{v:5d}" for v in chunk) + ",")

    text = (
        "/* cell_temp_table.c — GENERATED by App/bms/logic/gen_cell_temp.py from the\n"
        "   Enepaq datasheet Rev E, Table 5. Do not edit: change the script and run it.\n"
        "\n"
        "   Entry i is the temperature of a sensor reading of CELL_TEMP_MV_MIN + i\n"
        "   millivolts, in 0.1 C (cell_temp.h). */\n"
        "\n"
        "#include \"cell_temp.h\"\n"
        "\n"
        f"_Static_assert(CELL_TEMP_MV_MIN == {MV_MIN}u && CELL_TEMP_MV_MAX == {MV_MAX}u,\n"
        "               \"the table covers the sensor's range\");\n"
        "\n"
        "extern const int16_t cell_temp_table[CELL_TEMP_MV_MAX - CELL_TEMP_MV_MIN + 1u];\n"
        "\n"
        "const int16_t cell_temp_table[CELL_TEMP_MV_MAX - CELL_TEMP_MV_MIN + 1u] = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )
    OUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
