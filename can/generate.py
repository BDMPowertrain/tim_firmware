#!/usr/bin/env python3
"""Generates the C pack and unpack code from the Message database (ADR 0003).

    pip install -r requirements.txt
    python can/generate.py

Reads can/control.dbc and can/daq.dbc and rewrites
App/common/logic/can_db/can_control.[ch] and can_daq.[ch]. The output is
committed; CI runs this script and fails if anything changes. Never edit the
generated files: change the DBC and run this again.

A frame that comes once per module (BMS_CellTemps_00 to _15 and so on) gets
C for its _00 copy only: sixteen copies of the same code would be about
forty thousand lines. This script checks that the copies really are the
same, so the firmware packs any module with the _00 code and adds to the
_00 frame ID.

The C carries raw signal values only: the scaling helpers cantools can add
are left out, because they pass every unsigned value through a double and
logic never uses double (ADR 0002). A signal's scale and unit are in the DBC;
logic works in the raw unit (tenths of an amp and so on).

The output must be the same on every machine, so this script pins what the
cantools command line leaves loose: the date cantools prints in the file
header is removed, and line endings are always LF.
"""

import re
import sys
from pathlib import Path

import cantools
from cantools.database.can.c_source import generate

REPO = Path(__file__).resolve().parent.parent
OUT_DIR = REPO / "App" / "common" / "logic" / "can_db"

# DBC file -> name of the generated files and prefix of every generated symbol.
DATABASES = {
    "control.dbc": "can_control",
    "daq.dbc": "can_daq",
}

# "... generated by cantools version 1.2.3 Mon Jan  1 00:00:00 2026."
DATE_IN_HEADER = re.compile(r"(generated by cantools version [0-9.]+) [^\n]*\.\n")


def layout(message):
    """What must be equal between the copies of a per-module frame."""
    return (
        message.length,
        message.cycle_time,
        message.is_extended_frame,
        message.is_fd,
        [
            (s.name, s.start, s.length, s.byte_order, s.is_signed, s.is_float,
             s.conversion.scale, s.conversion.offset, s.minimum, s.maximum,
             s.unit, s.choices, s.multiplexer_ids)
            for s in message.signals
        ],
    )


def check_module_copies(database, dbc_name):
    """Frames named <Name>_00 to <Name>_15 are one frame repeated per module.

    Checks that every copy has the _00 layout and that the IDs are evenly
    spaced, and returns the copies other than _00.
    """
    families = {}
    for message in database.messages:
        match = re.fullmatch(r"(.+)_(\d\d)", message.name)
        if match:
            families.setdefault(match.group(1), {})[int(match.group(2))] = message

    for name, copies in families.items():
        if sorted(copies) != list(range(len(copies))) or len(copies) < 2:
            sys.exit(f"{dbc_name}: a frame name ending in _NN is a per-module "
                     f"frame, and {name}_NN is not numbered 00 upward without gaps")
        first = copies[0]
        stride = copies[1].frame_id - first.frame_id
        if stride <= 0:
            sys.exit(f"{dbc_name}: the IDs of {name}_NN do not go upward")
        for index, message in copies.items():
            if layout(message) != layout(first):
                sys.exit(f"{dbc_name}: {message.name} differs from {first.name}")
            if message.frame_id != first.frame_id + stride * index:
                sys.exit(f"{dbc_name}: {message.name} breaks the ID spacing of {name}_NN")
    return [m for copies in families.values() for i, m in copies.items() if i != 0]


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for dbc_name, c_name in DATABASES.items():
        database = cantools.database.load_file(REPO / "can" / dbc_name, strict=True)
        repeats = check_module_copies(database, dbc_name)
        for_c = cantools.database.Database(
            messages=[m for m in database.messages if m not in repeats],
            nodes=database.nodes, buses=database.buses, version=database.version,
            dbc_specifics=database.dbc)

        # No scaling helpers: see the note on double at the top of this file.
        # use_float keeps double out of the range checks that remain.
        header, source, _, _ = generate(
            for_c, c_name, c_name + ".h", c_name + ".c", c_name + "_fuzzer.c",
            floating_point_numbers=False, bit_fields=False, use_float=True)

        for suffix, text in ((".h", header), (".c", source)):
            text, dates = DATE_IN_HEADER.subn(r"\1.\n", text)
            if dates != 1:
                sys.exit("the cantools file header has changed; update DATE_IN_HEADER")
            path = OUT_DIR / (c_name + suffix)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(REPO)}")


if __name__ == "__main__":
    main()
